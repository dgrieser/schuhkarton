'use strict';
(() => {
  const pick = () => {
    try { const l = localStorage.getItem('schuhkarton-lang'); if (l === 'de' || l === 'en') return l; } catch { /* private mode */ }
    const d = document.documentElement.dataset.lang; // server default (ui.language)
    if (d === 'de' || d === 'en') return d;
    return /^de\b/i.test(navigator.language || '') ? 'de' : 'en';
  };
  const lang = pick();
  document.documentElement.lang = lang;
  const dict = () => (window.I18N && window.I18N[lang]) || {};
  // t('Hallo {name}', {name}) → translated text with parameters filled in
  window.skLang = lang;
  // texts with a variable part (from the server) by pattern
  const byPattern = (k) => {
    for (const [re, to] of (window.I18N_RX && window.I18N_RX[lang]) || []) if (re.test(k)) return k.replace(re, to);
    // "IMG_1.jpg: <message>": keep the file name, translate the message
    const m = /^([^:]{1,200}): ([\s\S]+)$/.exec(k);
    if (m) { const d = dict(), r = d[m[2]] || byPattern(m[2]); if (r) return `${m[1]}: ${r}`; }
    return '';
  };
  // a key may carry a context after "||" for words German uses twice: t('Benutzer||Rolle')
  window.skT = (s, p) => {
    const k = String(s ?? '');
    const plain = k.includes('||') ? k.slice(0, k.indexOf('||')) : k;
    let r = plain;
    if (lang !== 'de' && k) {
      const d = dict(), kt = k.trim(); // server errors end with a line break
      r = d[k] || d[kt] || byPattern(kt) || plain;
    }
    if (p) r = r.replace(/\{(\w+)\}/g, (_, n) => (p[n] ?? ''));
    return r;
  };
  window.skSetLang = (l) => { try { localStorage.setItem('schuhkarton-lang', l); } catch { /* ignore */ } location.reload(); };
  // static texts: <el data-t="Deutsch">Deutsch</el>, <el data-t-title="…">
  window.skTranslate = (root = document) => {
    if (lang === 'de') return;
    for (const el of root.querySelectorAll('[data-t]')) el.textContent = window.skT(el.dataset.t);
    for (const a of ['title', 'placeholder', 'aria-label']) {
      for (const el of root.querySelectorAll(`[data-t-${a}]`)) el.setAttribute(a, window.skT(el.getAttribute(`data-t-${a}`)));
    }
  };
})();
